/**
 * Generates src/types.ts from the JSON Schemas. Run `pnpm generate`; `pnpm generate --check`
 * fails when the committed file is stale (used in CI).
 */
import { compile, type JSONSchema } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "types.ts");

function load(name: string): JSONSchema {
  return JSON.parse(readFileSync(join(root, "schemas", name), "utf8")) as JSONSchema;
}

const options = { bannerComment: "", additionalProperties: false, strictIndexSignatures: true };

async function main(): Promise<void> {
  const parts: string[] = [
    "/* eslint-disable */",
    "/**",
    " * GENERATED by scripts/generate-types.ts from schemas/*.schema.json. Do not edit.",
    " */",
    "",
  ];
  const layer = load("layer-schema.schema.json");
  parts.push(await compile({ ...layer, title: "LayerSchema" }, "LayerSchema", options));
  const profile = load("capture-profile.schema.json");
  parts.push(await compile({ ...profile, title: "CaptureProfile" }, "CaptureProfile", options));

  // The sync file is a oneOf of three titled documents: emit one type per document.
  const sync = load("sync.schema.json") as JSONSchema & { oneOf: JSONSchema[]; $defs: Record<string, JSONSchema> };
  for (const branch of sync.oneOf) {
    const title = String(branch.title);
    parts.push(await compile({ ...branch, $defs: sync.$defs, title }, title, options));
  }
  for (const name of ["change", "changeResult", "pullItem", "changeMeta"]) {
    const title = name[0]!.toUpperCase() + name.slice(1);
    const def = sync.$defs[name]!;
    parts.push(await compile({ ...def, $defs: sync.$defs, title }, title, options));
  }

  // De-duplicate helper types that several compiles emit identically.
  const seen = new Set<string>();
  const text = parts
    .join("\n")
    .split(/\n(?=export (?:interface|type) )/)
    .filter((chunk) => {
      const m = chunk.match(/^export (?:interface|type) (\w+)/);
      if (!m) return true;
      if (seen.has(m[1]!)) return false;
      seen.add(m[1]!);
      return true;
    })
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");

  if (process.argv.includes("--check")) {
    const current = readFileSync(out, "utf8");
    if (current !== text) {
      console.error("src/types.ts is stale: run `pnpm --filter @precisecapture/schema generate`");
      process.exit(1);
    }
    console.log("src/types.ts is up to date");
    return;
  }
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
